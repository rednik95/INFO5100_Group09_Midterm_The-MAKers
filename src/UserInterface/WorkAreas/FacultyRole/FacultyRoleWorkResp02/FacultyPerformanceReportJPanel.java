    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int selectedRow = performanceTable.getSelectedRow();

        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(this, "Please select a student.");
            return;
        }

        int modelRow = performanceTable.convertRowIndexToModel(selectedRow);

        University.CourseSchedule.SeatAssignment assignment
                = displayedAssignments.get(modelRow);

        String input = JOptionPane.showInputDialog(
                this,
                "Enter grade (0.0 - 4.0):",
                assignment.isGraded() ? String.valueOf(assignment.getGrade()) : ""
        );

        if (input == null) {
            return; // Cancel
        }

        try {
            float grade = Float.parseFloat(input.trim());

            if (!Float.isFinite(grade) || grade < 0.0f || grade > 4.0f) {
                throw new NumberFormatException();
            }

            assignment.setGrade(grade);

            refreshTable(searchTextField.getText().trim());

            JOptionPane.showMessageDialog(this, "Grade saved successfully.");

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                    "Please enter a valid grade between 0.0 and 4.0.");
        }
    }//GEN-LAST:event_jButton1ActionPerformed
    private void saveGrade(int row) {

        if (row < 0 || row >= displayedAssignments.size()) {
            return;
        }

        University.CourseSchedule.SeatAssignment assignment
                = displayedAssignments.get(row);

        Object value = performanceTable.getModel().getValueAt(row, 5);

        float grade;

        try {
            grade = Float.parseFloat(value.toString().trim());

            if (!Float.isFinite(grade) || grade < 0.0f || grade > 4.0f) {
                throw new NumberFormatException();
            }

        } catch (NumberFormatException | NullPointerException ex) {
            JOptionPane.showMessageDialog(this,
                    "Grade must be a number between 0.0 and 4.0.");

            refreshTable(searchTextField.getText().trim());
            return;
        }

        assignment.setGrade(grade);

        refreshTable(searchTextField.getText().trim());

        JOptionPane.showMessageDialog(this, "Grade saved successfully.");
    }

    public void refreshTable(String search) {

        DefaultTableModel model
                = (DefaultTableModel) performanceTable.getModel();

        refreshingTable = true;
        displayedAssignments.clear();
        model.setRowCount(0);

        University.Department.Department dept
                = business.getPrimaryDepartment();

        String facultyId = facultyProfile.getPerson().getPersonId();

        University.Persona.Faculty.FacultyProfile faculty
                = dept.getFacultyDirectory().findTeachingFaculty(facultyId);

        if (faculty == null) {
            refreshingTable = false;
            return;
        }

        for (University.Persona.StudentProfile student
                : dept.getStudentDirectory().getStudentList()) {

            String studentId = null;
            String studentName = null;

            // Match the University student with the Business student
            for (StudentProfile businessStudent
                    : business.getStudentDirectory().getStudentList()) {

                String id = businessStudent.getPerson().getPersonId();

                if (student.isMatch(id)) {
                    studentId = id;
                    studentName
                            = businessStudent.getPerson().getFirstName()
                            + " "
                            + businessStudent.getPerson().getLastName();
                    break;
                }
            }

            if (studentId == null) {
                continue;
            }

            for (University.CourseSchedule.SeatAssignment sa
                    : student.getCourseList()) {

                University.CourseSchedule.CourseOffer offer
                        = sa.getCourseOffer();

                boolean taughtByFaculty = false;

                for (University.Persona.Faculty.FacultyAssignment assignment
                        : faculty.getFacultyAssignments()) {

                    if (assignment.getCourseOffer() == offer) {
                        taughtByFaculty = true;
                        break;
                    }
                }

                if (!taughtByFaculty) {
                    continue;
                }

                String course = offer.getCourseNumber();
                String semester = sa.getCourseLoad().getSemester();

                if (!studentId.toLowerCase().contains(search.toLowerCase())
                        && !studentName.toLowerCase().contains(search.toLowerCase())
                        && !course.toLowerCase().contains(search.toLowerCase())
                        && !semester.toLowerCase().contains(search.toLowerCase())) {
                    continue;
                }

                String grade = sa.isGraded()
                        ? String.valueOf(sa.getGrade())
                        : "—";

                String status = sa.isGraded()
                        ? "Graded"
                        : "In Progress";

                model.addRow(new Object[]{
                    studentId,
                    studentName,
                    course,
                    semester,
                    sa.getCreditHours(),
                    grade,
                    status
                });
                displayedAssignments.add(sa);
            }
        }
        refreshingTable = false;
    }

