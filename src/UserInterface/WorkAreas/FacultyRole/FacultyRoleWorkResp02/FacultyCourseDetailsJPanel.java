    private void refreshSemesterTable() {

        DefaultTableModel model
                = (DefaultTableModel) jTable1.getModel();

        model.setRowCount(0);

        for (CourseSchedule schedule
                : business.getPrimaryDepartment().getCourseSchedules().values()) {

            for (CourseOffer offer : schedule.getCourseOffers()) {

                if (offer.getSubjectCourse() == selectedCourse) {

                    Object[] row = {
                        schedule.getSemester(),
                        ((java.util.ArrayList<?>) offer.getSeatList()).size()
                    };

                    model.addRow(row);
                }
            }
        }
    }

