    private void NextActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_NextActionPerformed

        // Validate required fields
        if (firstNameTextField.getText().trim().isEmpty()
                || lastNameTextField.getText().trim().isEmpty()
                || emailTextField.getText().trim().isEmpty()
                || usernameTextField.getText().trim().isEmpty()
                || departmentTextField.getText().trim().isEmpty()) {

            AppUtils.missingFields(this, "All fields");
            return;
        }

        if (passwordField.getPassword().length == 0) {
            AppUtils.missingFields(this, "Password");
            return;
        }

        if (!java.util.Arrays.equals(
                passwordField.getPassword(),
                confirmPasswordField.getPassword())) {
            AppUtils.passwordMismatch(this);
            return;
        }
        String nuid = usernameTextField.getText().trim();

        for (StudentProfile student : business.getStudentDirectory().getStudentList()) {
            if (student.getNuid().equals(nuid)) {
                JOptionPane.showMessageDialog(
                        this,
                        "This NUID is already registered."
                );
                return;
            }
        }

        // Create person
        Person person = business.getPersonDirectory().newPerson(
                firstNameTextField.getText().trim(),
                lastNameTextField.getText().trim(),
                emailTextField.getText().trim(),
                ""
        );

        StudentProfile student = business.getStudentDirectory().newStudentProfile(
                person,
                usernameTextField.getText().trim(),
                departmentTextField.getText().trim()
        );

        student.setActivationCode(new String(passwordField.getPassword()));

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Student registered successfully."
        );
        
        for (java.awt.Component component : CardSequencePanel.getComponents()) {
            if (component instanceof ManageStudentsJPanel) {
                ((ManageStudentsJPanel) component).refreshTable("");
            }
        }
        // Return to Admin menu
        ((java.awt.CardLayout) CardSequencePanel.getLayout())
                .previous(CardSequencePanel);

    }//GEN-LAST:event_NextActionPerformed


