    /**
     * @Desc: Populates the UI fields from the current account.
     */
    private void loadAccount() {

        Profile profile = account.getAssociatedPersonProfile();
        Person person = profile.getPerson();

        roleCombo.setSelectedItem(profile.getRole());

        employeeIdTextField.setText(person.getPersonId());
        firstNameTextField.setText(person.getFirstName());
        lastNameTextField.setText(person.getLastName());
        emailTextField.setText(person.getEmail());
        phoneNumberTextField.setText(person.getPhoneNumber());

        usernameTextField.setText(account.getUserLoginName());
        statusCombo.setSelectedItem(account.getStatus());

        if (profile instanceof EmployeeProfile) {
            EmployeeProfile employee = (EmployeeProfile) profile;

            departmentTextField.setText(employee.getDepartment());
            jobTitleTextField.setText(employee.getJobTitle());
            hireDateSpinner.setValue(employee.getHireDate());

        } else if (profile instanceof FacultyProfile) {
            FacultyProfile faculty = (FacultyProfile) profile;

            departmentTextField.setText(faculty.getDepartment());
            jobTitleTextField.setText(faculty.getSubject());
            hireDateSpinner.setValue(faculty.getHireDate());
        }

        passwordField.setText("");
        confirmPasswordField.setText("");
    }

    /**
     * @Desc: Enables editable mode when the Edit button is clicked.
     */
    private void setEditMode(boolean editing) {

        firstNameTextField.setEditable(editing);
        lastNameTextField.setEditable(editing);
        emailTextField.setEditable(editing);
        phoneNumberTextField.setEditable(editing);
        usernameTextField.setEditable(editing);

        passwordField.setEditable(editing);
        confirmPasswordField.setEditable(editing);

        departmentTextField.setEditable(editing);
        jobTitleTextField.setEditable(editing);

        hireDateSpinner.setEnabled(editing);
        statusCombo.setEnabled(editing && !myProfile);

        roleCombo.setEnabled(false);
        employeeIdTextField.setEditable(false);

        this.editing = editing;

        editButton.setVisible(!editing);
        Next.setVisible(editing);

    }

