    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        //TODO add your handling code here:
                                  
    int selectedRow = jTable2.getSelectedRow();
    if (selectedRow < 0) {
        JOptionPane.showMessageDialog(this, "Please select a course from the catalog to enroll.", "Warning", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Get the table models
    DefaultTableModel catalogModel = (DefaultTableModel) jTable2.getModel();
    DefaultTableModel enrolledModel = (DefaultTableModel) jTable4.getModel();

    try {
        // Assuming column 6 is 'Seat' (0-indexed: ID, Name, Credit, Semester, Type, Instructor, Seat)
        // Adjust index if  column order is different
        Object seatObj = catalogModel.getValueAt(selectedRow, 6);
        int currentSeats = 0;
        
        if (seatObj != null) {
            currentSeats = Integer.parseInt(seatObj.toString());
        }

        if (currentSeats <= 0) {
            JOptionPane.showMessageDialog(this, "Sorry, this course is fully booked (0 seats available).", "Registration Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // 1. Subtract 1 from the seat count and update catalog table
        currentSeats--;
        catalogModel.setValueAt(currentSeats, selectedRow, 6);

        // 2. Extract course details to move to enrolled schedule
        String courseId = catalogModel.getValueAt(selectedRow, 0).toString();
        String courseName = catalogModel.getValueAt(selectedRow, 1).toString();
        String credit = catalogModel.getValueAt(selectedRow, 2).toString();
        String semester = catalogModel.getValueAt(selectedRow, 3).toString();
        String type = catalogModel.getValueAt(selectedRow, 4).toString();
        
        // Default initial grade (e.g., "In Progress" or "-")
        String grade = "In Progress"; 

        // 3. Add row to Enrolled table (jTable4 columns: ID, Name, Credit, Semester, Type, Grade)
        enrolledModel.addRow(new Object[]{courseId, courseName, credit, semester, type, grade});

        JOptionPane.showMessageDialog(this, "Successfully enrolled in " + courseName + "!");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Invalid seat format in table data.", "Error", JOptionPane.ERROR_MESSAGE);
    }

        
        
    }//GEN-LAST:event_btnAddActionPerformed

