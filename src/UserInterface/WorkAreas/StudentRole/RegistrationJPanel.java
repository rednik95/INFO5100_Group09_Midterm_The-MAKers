    private void btnDropActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDropActionPerformed
        // TODO add your handling code here:
        int selectedRow = jTable4.getSelectedRow();
    if (selectedRow < 0) {
        JOptionPane.showMessageDialog(this, "Please select a course from your enrolled schedule to drop.", "Warning", JOptionPane.WARNING_MESSAGE);
        return;
    }

    DefaultTableModel enrolledModel = (DefaultTableModel) jTable4.getModel();
    DefaultTableModel catalogModel = (DefaultTableModel) jTable2.getModel();

    String droppedCourseId = enrolledModel.getValueAt(selectedRow, 0).toString();

    // Find the course back in the catalog table and increment its seat count by 1
    for (int i = 0; i < catalogModel.getRowCount(); i++) {
        String catalogCourseId = catalogModel.getValueAt(i, 0) != null ? catalogModel.getValueAt(i, 0).toString() : "";
        if (catalogCourseId.equals(droppedCourseId)) {
            Object seatObj = catalogModel.getValueAt(i, 6);
            int currentSeats = (seatObj != null) ? Integer.parseInt(seatObj.toString()) : 0;
            catalogModel.setValueAt(currentSeats + 1, i, 6);
            break;
        }
    }

    // Remove the course from the enrolled table
    enrolledModel.removeRow(selectedRow);
    JOptionPane.showMessageDialog(this, "Course successfully dropped and seat restored.");

    }//GEN-LAST:event_btnDropActionPerformed

    

