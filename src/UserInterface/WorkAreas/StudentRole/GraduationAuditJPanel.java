    private void populateTables() {
        // Define credit requirements for Core and Electives
        int coreRequired = 16;
        int coreCompleted = 16; //  pull this from student transcript data if available
        
        int electiveRequired = 16;
        int electiveCompleted = 12; // Example: student has completed 12 out of 16 elective credits
        
        // Calculate totals dynamically
        int totalRequired = coreRequired + electiveRequired;
        int totalCompleted = coreCompleted + electiveCompleted;
        int totalRemaining = Math.max(0, totalRequired - totalCompleted);

        // 1. Populate jTable3 (Credit Summary: Total Required, Completed, Remaining)
        javax.swing.table.DefaultTableModel summaryModel = (javax.swing.table.DefaultTableModel) tbtGraduationAudit.getModel();
        summaryModel.setRowCount(0);
        summaryModel.addRow(new Object[]{totalRequired, totalCompleted, totalRemaining});

        // 2. Populate jTable4 (Requirements Breakdown with dynamic status matching)
        javax.swing.table.DefaultTableModel reqModel = (javax.swing.table.DefaultTableModel) tbtRequirement.getModel();
        reqModel.setRowCount(0);
        
        // Core Row Status Logic
        String coreStatus = (coreCompleted >= coreRequired) ? "Complete" : "In Progress";
        reqModel.addRow(new Object[]{"Core", coreRequired, coreCompleted, coreStatus});
        
        // Elective Row Status Logic
        String electiveStatus = (electiveCompleted >= electiveRequired) ? "Complete" : "In Progress";
        reqModel.addRow(new Object[]{"Elective", electiveRequired, electiveCompleted, electiveStatus});
        
        // Total Summary Row
        String overallStatus = (totalCompleted >= totalRequired) ? "Complete" : totalRemaining + " remaining";
        reqModel.addRow(new Object[]{"Total", totalRequired, totalCompleted, overallStatus});
        
    
    }

