    private void signUpButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_signUpButtonActionPerformed
        String nuid = nuidTextField.getText().trim();
        char[] code = activationCodeField.getPassword();
        char[] password = passwordField.getPassword();
        char[] confirmation = confirmPasswordField.getPassword();

        if (nuid.isEmpty() || code.length == 0
                || password.length == 0 || confirmation.length == 0) {
            AppUtils.missingFields(this, "All fields");
            return;
        }

        if (!Arrays.equals(password, confirmation)) {
            AppUtils.passwordMismatch(this);
            return;
        }

        // Find student by NUID
        StudentProfile student = null;

        for (StudentProfile sp : business.getStudentDirectory().getStudentList()) {
            if (sp.getNuid().equals(nuid)) {
                student = sp;
                break;
            }
        }

        if (student == null
                || student.getActivationCode() == null
                || !student.getActivationCode().equals(new String(code))) {

            JOptionPane.showMessageDialog(this, "Invalid NUID or activation code.");
            return;
        }

        // Prevent duplicate accounts
        for (UserAccount account : business.getUserAccountDirectory().getUserAccountList()) {
            if (account.getAssociatedPersonProfile() == student) {
                JOptionPane.showMessageDialog(this, "Account already activated.");
                return;
            }
        }

        if (business.getUserAccountDirectory().usernameExists(nuid, null)) {
            JOptionPane.showMessageDialog(
                    this,
                    "This NUID is already used as a username.",
                    "Duplicate username",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        // Create student account
        business.getUserAccountDirectory().newUserAccount(
                student,
                nuid,
                new String(password),
                true,
                null,
                new Date()
        );

        // Activation code can no longer be used
        student.clearActivationCode();

        JOptionPane.showMessageDialog(this, "Account activated successfully.");
    }//GEN-LAST:event_signUpButtonActionPerformed


