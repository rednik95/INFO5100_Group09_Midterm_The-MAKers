    private void populateCourseTable() {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        model.setRowCount(0); // Clear blank placeholder rows

        java.util.ArrayList<StudentCourseRecord> records = StudentAcademicModel.getRecordsForStudent(student);

        // Pre-populate: add the sample course to the shared model once
        boolean hasDamg = false;
        for (StudentCourseRecord r : records) {
            if ("DAMG 6210".equalsIgnoreCase(r.getCourseNumber())) {
                hasDamg = true;
                break;
            }
        }
        if (!hasDamg) {
            records.add(new StudentCourseRecord("DAMG 6210", "Database Management & Design", 4,
                    "Fall 2026", "Elective", "Prof. A. Chen", "In Progress",
                    "Course Started", 25));
        }

        for (StudentCourseRecord r : records) {
            boolean inProgress = "In Progress".equalsIgnoreCase(r.getGrade());
            model.addRow(new Object[]{
                r.getCourseNumber(),
                r.getCourseName(),
                r.getSemester(),
                r.getGrade(),
                r.getCredits(),
                inProgress ? "Enrolled" : "Completed"
            });
        }
    }
    
