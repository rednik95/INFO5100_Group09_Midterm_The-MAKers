    private void refreshTranscript() {
        String selectedTerm = cmbSemester.getSelectedItem().toString();
        DefaultTableModel model = (DefaultTableModel) transcriptTable.getModel();
        model.setRowCount(0);

        for (StudentCourseRecord r : StudentAcademicModel.getRecordsForStudent(student)) {
            if ("All Semesters".equals(selectedTerm) || r.getSemester().equalsIgnoreCase(selectedTerm)) {
                double gp = r.getGradePoints();
                String qualityPts = (gp >= 0.0) ? String.format("%.1f", gp * r.getCredits()) : "N/A";
                model.addRow(new Object[]{
                    r.getSemester(),
                    r.getCourseNumber(),
                    r.getCourseName(),
                    r.getRequirementType(),
                    r.getCredits(),
                    r.getGrade(),
                    qualityPts
                });
            }
        }

        double earned = StudentAcademicModel.getCompletedCredits(student);
        double gpa = StudentAcademicModel.calculateCumulativeGPA(student);
        
        String standing = (gpa >= 3.5) ? "Dean's List" : (gpa >= 3.0 ? "Good Standing" : "Academic Probation");
    }


